"""CLIP embeddings of token images and texts, and captions for image-topic labels.

Follows Steffen (ICWSM 2025), "More than Memes: A Multimodal Topic Modeling Approach to Conspiracy
Theories on Telegram": images and texts are embedded with sentence-transformers' ``clip-ViT-B-32``,
and image topics are labelled from captions generated by ``nlpconnect/vit-gpt2-image-captioning``.

Embeddings are L2-normalised and stored as float16 bytes (``emb`` column, 512 values = 1 KB), one
Parquet file per input file so every step is resumable. Usage::

    python -m crypto_analysis.clip_embeddings images   --out-dir data/clip
    python -m crypto_analysis.clip_embeddings texts    --out-dir data/clip
    python -m crypto_analysis.clip_embeddings captions --out-dir data/clip --sample 100000
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import io
from pathlib import Path
import time

import numpy as np
import pandas as pd
from PIL import Image
import pyarrow.parquet as pq

from crypto_analysis.datalake import DATA_DIR

CLIP_MODEL = "clip-ViT-B-32"
CAPTION_MODEL = "nlpconnect/vit-gpt2-image-captioning"
DIM = 512


def to_bytes(emb):
    """float32/16 matrix -> list of float16 byte strings (one per row)."""
    emb = np.asarray(emb, dtype=np.float16)
    return [row.tobytes() for row in emb]


def from_bytes(column):
    """Inverse of ``to_bytes``: a sequence of byte strings -> (n, 512) float16 matrix."""
    return np.frombuffer(b"".join(column), dtype=np.float16).reshape(-1, DIM)


def load_embeddings(directory, key):
    """Concatenate a directory of embedding files into ``(keys, matrix)``."""
    files = sorted(Path(directory).glob("*.parquet"))
    tables = [pq.read_table(f, columns=[key, "emb"]) for f in files]
    keys = np.concatenate([t[key].to_numpy(zero_copy_only=False) for t in tables]) if tables else np.array([])
    matrix = np.concatenate([from_bytes(t["emb"].to_pylist()) for t in tables]) if tables else np.empty((0, DIM))
    return keys, matrix


def topic_sample(image_keys, n, seed=42):
    """The deterministic sample of distinct images used to fit image topics (and to caption)."""
    keys = np.sort(np.asarray(image_keys))
    rng = np.random.default_rng(seed)
    return keys[rng.choice(len(keys), size=min(n, len(keys)), replace=False)]


def _model(device="cuda"):
    from sentence_transformers import SentenceTransformer  # heavy import, only when encoding

    model = SentenceTransformer(CLIP_MODEL, device=device)
    if device == "cuda":
        model.half()
    return model


def _decode(raw):
    try:
        return Image.open(io.BytesIO(raw)).convert("RGB")
    except (OSError, ValueError):
        return None


def embed_images(out_dir, images_dir, batch_size=256, threads=8):
    out = Path(out_dir) / "images"
    out.mkdir(parents=True, exist_ok=True)
    shards = sorted(Path(images_dir).glob("shard_*.parquet"))
    todo = [s for s in shards if not (out / s.name).exists()]
    print(f"{len(shards)} shards, {len(todo)} to embed", flush=True)
    model = _model()
    start = time.time()
    with ThreadPoolExecutor(threads) as pool:
        for k, shard in enumerate(todo, 1):
            table = pq.read_table(shard, columns=["sha256", "bytes"])
            imgs = list(pool.map(_decode, table["bytes"].to_pylist()))
            ok = [i for i, im in enumerate(imgs) if im is not None]
            emb = model.encode([imgs[i] for i in ok], batch_size=batch_size, convert_to_numpy=True,
                               normalize_embeddings=True, show_progress_bar=False)
            shas = table["sha256"].to_pylist()
            df = pd.DataFrame({"sha256": [shas[i] for i in ok], "emb": to_bytes(emb)})
            tmp = out / f"{shard.stem}.parquet.tmp"
            df.to_parquet(tmp, index=False)
            tmp.rename(out / shard.name)
            elapsed = time.time() - start
            print(f"[{k}/{len(todo)}] {shard.name}: {len(df):,} images ({elapsed / 60:.1f} min, "
                  f"~{elapsed / k * (len(todo) - k) / 60:.1f} min left)", flush=True)


def token_text(meta_name, description, max_chars=300):
    """The text embedded for a token: "name. description", trimmed (CLIP reads 77 tokens at most)."""
    name = "" if meta_name is None or pd.isna(meta_name) else str(meta_name).strip()
    desc = "" if description is None or pd.isna(description) else str(description).strip()
    text = f"{name}. {desc}" if desc else name
    return text[:max_chars]


def embed_texts(out_dir, data_dir, batch_size=1024):
    out = Path(out_dir) / "texts"
    out.mkdir(parents=True, exist_ok=True)
    files = sorted((Path(data_dir) / "parquet" / "token_metadata").glob("token_metadata_*.parquet"))
    todo = [f for f in files if not (out / f"{f.stem[-10:]}.parquet").exists()]
    print(f"{len(files)} metadata days, {len(todo)} to embed", flush=True)
    model = _model()
    start = time.time()
    for k, f in enumerate(todo, 1):
        meta = pd.read_parquet(f, columns=["mint", "meta_name", "description", "status"])
        meta = meta[meta.status == "ok"].drop_duplicates("mint")
        texts = [token_text(n, d) for n, d in zip(meta.meta_name, meta.description)]
        keep = [i for i, t in enumerate(texts) if t]
        emb = model.encode([texts[i] for i in keep], batch_size=batch_size, convert_to_numpy=True,
                           normalize_embeddings=True, show_progress_bar=False)
        df = pd.DataFrame({"mint": meta.mint.to_numpy()[keep], "emb": to_bytes(emb)})
        tmp = out / f"{f.stem[-10:]}.parquet.tmp"
        df.to_parquet(tmp, index=False)
        tmp.rename(out / f"{f.stem[-10:]}.parquet")
        elapsed = time.time() - start
        print(f"[{k}/{len(todo)}] {f.stem[-10:]}: {len(df):,} texts ({elapsed / 60:.1f} min, "
              f"~{elapsed / k * (len(todo) - k) / 60:.1f} min left)", flush=True)


def caption_images(out_dir, images_dir, data_dir, sample, batch_size=128, seed=42):
    """Captions for the topic-model sample (vit-gpt2, greedy decoding, as in the reference paper)."""
    import torch
    from transformers import AutoTokenizer, VisionEncoderDecoderModel, ViTImageProcessor

    out = Path(out_dir) / "captions.parquet"
    keys, _ = load_embeddings(Path(out_dir) / "images", "sha256")
    wanted = set(topic_sample(keys, sample, seed))
    model = VisionEncoderDecoderModel.from_pretrained(CAPTION_MODEL).to("cuda").half().eval()
    processor = ViTImageProcessor.from_pretrained(CAPTION_MODEL)
    tokenizer = AutoTokenizer.from_pretrained(CAPTION_MODEL)
    rows, start = [], time.time()
    for shard in sorted(Path(images_dir).glob("shard_*.parquet")):
        table = pq.read_table(shard, columns=["sha256", "bytes"]).to_pandas()
        table = table[table.sha256.isin(wanted)]
        for s in range(0, len(table), batch_size):
            batch = table.iloc[s:s + batch_size]
            imgs = [_decode(b) for b in batch.bytes]
            pairs = [(sha, im) for sha, im in zip(batch.sha256, imgs) if im is not None]
            if not pairs:
                continue
            pixels = processor(images=[im for _, im in pairs], return_tensors="pt").pixel_values.to("cuda").half()
            with torch.no_grad():
                ids = model.generate(pixels, max_length=16, num_beams=1)
            caps = tokenizer.batch_decode(ids, skip_special_tokens=True)
            rows += [(sha, c.strip()) for (sha, _), c in zip(pairs, caps)]
        print(f"{shard.name}: {len(rows):,} captions ({(time.time() - start) / 60:.1f} min)", flush=True)
    pd.DataFrame(rows, columns=["sha256", "caption"]).to_parquet(out, index=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("step", choices=["images", "texts", "captions"])
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    parser.add_argument("--sample", type=int, default=100_000, help="captions: images in the topic sample")
    args = parser.parse_args()
    if args.step == "images":
        embed_images(args.out_dir, args.data_dir / "images")
    elif args.step == "texts":
        embed_texts(args.out_dir, args.data_dir)
    else:
        caption_images(args.out_dir, args.data_dir / "images", args.data_dir, args.sample)


if __name__ == "__main__":
    main()
